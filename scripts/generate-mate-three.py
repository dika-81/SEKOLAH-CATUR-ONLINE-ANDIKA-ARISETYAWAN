"""Rebuild authored endgame puzzles: python -m pip install python-chess first.

Only a development tool; the website and npm tests do not depend on Python.
Exhaustive legal-move search proves every defense, including quiet moves.
"""
import json
import random
from pathlib import Path

import chess

rng = random.Random(20261024)
cache = {}


def wins(board, plies):
    key = (board._transposition_key(), plies)
    if key in cache:
        return cache[key]
    moves = list(board.legal_moves)
    if not moves:
        return board.turn == chess.BLACK and board.is_check()
    if plies == 0 or board.is_insufficient_material():
        return False
    attacking = board.turn == chess.WHITE
    # Checking moves first is only an ordering optimization, never a filter.
    if attacking:
        moves.sort(key=lambda move: board.gives_check(move), reverse=True)
    result = not attacking
    for move in moves:
        board.push(move)
        child = wins(board, plies - 1)
        board.pop()
        if child == attacking:
            result = attacking
            break
    cache[key] = result
    return result


def proof(board, plies):
    if board.is_checkmate():
        return {"plies": 0, "moves": {}}
    children = {}
    attacking = board.turn == chess.WHITE
    for move in list(board.legal_moves):
        board.push(move)
        if wins(board, plies - 1):
            children[move.uci()] = proof(board, plies - 1)
        elif not attacking:
            raise ValueError("A defense escapes mate")
        board.pop()
    distances = [child["plies"] + 1 for child in children.values()]
    return {"plies": (min if attacking else max)(distances), "moves": children}


families = [
    ("menteri", "Kerja sama raja dan menteri", "q"),
    ("benteng", "Raja membantu benteng", "r"),
    ("dua-benteng", "Jaring dua benteng", "rr"),
    ("menteri-kuda", "Menteri bersama kuda", "qn"),
    ("benteng-gajah", "Benteng bersama gajah", "rb"),
    ("dua-gajah", "Dua gajah menutup jalan", "bb"),
]


def generate():
    target = Path(__file__).resolve().parents[1] / "data" / "mate-three.js"
    puzzles = []
    for family, title, material in families:
        accepted = set()
        attempts = 0
        while len(accepted) < 6:
            attempts += 1
            cache.clear()
            board = chess.Board(None)
            # Near an edge, with the white king close enough to support mate.
            bk = rng.choice([s for s in chess.SQUARES if chess.square_rank(s) >= 6])
            wk = rng.choice([s for s in chess.SQUARES if 2 <= chess.square_distance(s, bk) <= 4])
            occupied = {bk, wk}
            board.set_piece_at(bk, chess.Piece(chess.KING, chess.BLACK))
            board.set_piece_at(wk, chess.Piece(chess.KING, chess.WHITE))
            for symbol in material:
                square = rng.choice([s for s in chess.SQUARES if s not in occupied])
                occupied.add(square)
                board.set_piece_at(square, chess.Piece.from_symbol(symbol.upper()))
            if not board.is_valid() or board.fen() in accepted:
                continue
            if wins(board, 3) or not wins(board, 5):
                continue
            tree = proof(board, 5)
            assert tree["plies"] == 5
            accepted.add(board.fen())
            index = len(accepted)
            puzzles.append({"id": f"mat3-{family}-{index}", "title": f"{title} {index}",
                            "theme": title, "fen": board.fen(), "tree": tree})
            print(f"{len(puzzles):02d}: {family} ({attempts} candidates)", flush=True)
            target.write_text("// Generated by scripts/generate-mate-three.py; all legal defenses verified.\n"
                              + "export const mateThreePuzzles = [\n"
                              + ",\n".join(json.dumps(p, ensure_ascii=False, separators=(",", ":")) for p in puzzles)
                              + "\n];\n", encoding="utf-8")


if __name__ == "__main__":
    generate()
